import assert from 'node:assert/strict';
import { spawn } from 'node:child_process';
import { once } from 'node:events';
import {
  chmod,
  mkdir,
  mkdtemp,
  readFile,
  rm,
  writeFile,
} from 'node:fs/promises';
import { createRequire } from 'node:module';
import { tmpdir } from 'node:os';
import path from 'node:path';
import test from 'node:test';
import { setTimeout as delay } from 'node:timers/promises';

const require = createRequire(import.meta.url);
const cli = path.join(
  path.dirname(require.resolve('@tauri-apps/cli')),
  'tauri.js',
);

for (const ignoreGenerated of [false, true]) {
  test(
    ignoreGenerated
      ? 'generated embedding resources do not restart dev, but native sources still do'
      : 'unignored generated resources reproduce a dev rebuild',
    {
      timeout: 30000,
      skip: process.platform === 'win32',
    },
    async () => {
      const directory = await mkdtemp(
        path.join(tmpdir(), 'daydream-dev-watch-'),
      );
      const native = path.join(directory, 'src-tauri');
      const trace = path.join(directory, 'runs.jsonl');
      let child;
      let output = '';
      async function runs() {
        try {
          return (await readFile(trace, 'utf8'))
            .trim()
            .split('\n')
            .filter(Boolean)
            .map(JSON.parse);
        } catch (error) {
          if (error.code === 'ENOENT') return [];
          throw error;
        }
      }
      async function waitFor(predicate) {
        for (let attempt = 0; attempt < 100; attempt += 1) {
          if (await predicate()) return;
          if (child.exitCode !== null)
            throw new Error(`Tauri dev exited: ${output}`);
          await delay(100);
        }
        throw new Error(`Tauri watcher did not settle: ${output}`);
      }
      try {
        await Promise.all([
          mkdir(path.join(native, 'src'), { recursive: true }),
          mkdir(path.join(native, 'resources/embedding'), { recursive: true }),
          mkdir(path.join(directory, 'tauri-stub/src'), { recursive: true }),
        ]);
        const runner = path.join(directory, 'runner.mjs');
        await Promise.all([
          writeFile(
            path.join(native, 'Cargo.toml'),
            '[package]\nname="watch-fixture"\nversion="0.0.0"\nedition="2021"\n[dependencies]\ntauri={path="../tauri-stub"}\n',
          ),
          writeFile(
            path.join(directory, 'tauri-stub/Cargo.toml'),
            '[package]\nname="tauri"\nversion="2.12.1"\nedition="2021"\n',
          ),
          writeFile(path.join(directory, 'tauri-stub/src/lib.rs'), ''),
          writeFile(path.join(native, 'src/main.rs'), 'fn main() {}\n'),
          writeFile(
            path.join(native, 'tauri.conf.json'),
            JSON.stringify({
              productName: 'Watcher fixture',
              version: '0.0.0',
              identifier: 'test.daydream.watcher',
              build: { devUrl: 'http://localhost:9' },
              bundle: { active: false },
            }),
          ),
          writeFile(
            path.join(native, '.taurignore'),
            ignoreGenerated
              ? await readFile(
                  new URL('../src-tauri/.taurignore', import.meta.url),
                )
              : '',
          ),
          writeFile(
            runner,
            '#!/usr/bin/env node\nimport {appendFileSync} from "node:fs";\nappendFileSync(process.env.DAYDREAM_WATCH_TRACE, JSON.stringify({pid:process.pid})+"\\n");\nsetInterval(()=>{},1000);\n',
          ),
        ]);
        await chmod(runner, 0o755);
        child = spawn(
          process.execPath,
          [
            cli,
            'dev',
            '--runner',
            runner,
            '--no-dev-server-wait',
            '--no-dev-server',
          ],
          {
            cwd: directory,
            detached: true,
            env: { ...process.env, DAYDREAM_WATCH_TRACE: trace },
            stdio: ['ignore', 'pipe', 'pipe'],
          },
        );
        child.stdout.on('data', (chunk) => {
          output += chunk;
        });
        child.stderr.on('data', (chunk) => {
          output += chunk;
        });
        await waitFor(
          async () =>
            (await runs()).length === 1 && output.includes('Watching'),
        );
        // Several generated artifacts change while the real CLI watcher is active.
        for (const file of [
          'daydream-embedding-worker',
          'daydream-embedding-worker-vulkan',
          'LLAMA-LICENSE.txt',
        ]) {
          await writeFile(
            path.join(native, 'resources/embedding', file),
            'generated bytes\n',
          );
        }
        if (ignoreGenerated) await delay(1500);
        else await waitFor(async () => (await runs()).length >= 2);
        const expected = ignoreGenerated ? 1 : 2;
        assert.equal((await runs()).length, expected, output);
        await writeFile(
          path.join(native, 'src/main.rs'),
          'fn main() {} // source edit\n',
        );
        await waitFor(async () => (await runs()).length >= expected + 1);
        assert.equal((await runs()).length, expected + 1, output);
        assert.match(output, /src\/main.rs.*Rebuilding application/s);
      } finally {
        if (child) {
          try {
            process.kill(-child.pid, 'SIGTERM');
          } catch {
            /* already stopped */
          }
          if (child.exitCode === null) await once(child, 'exit');
          for (const { pid } of await runs()) {
            try {
              process.kill(pid, 'SIGTERM');
            } catch {
              /* already stopped */
            }
          }
        }
        await rm(directory, { recursive: true, force: true });
      }
    },
  );
}
